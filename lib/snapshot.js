define(["qlik", "./util", "./dashboard", "./cssscope", "./appinfo", "./session", "./i18n"], function (qlik, u, dash, cssscope, appinfo, session, i18n) {
  "use strict";

  var T = i18n.T;

  // HTML Complexo: o painel é montado fora da tela, com os dados extraídos agora, e vira uma página
  // autônoma (sem Qlik, sem scripts externos) que pode ser baixada ou aberta numa aba.
  // Os cubos rodam numa sessão separada do app (identity), no estado padrão: lá as seleções começam
  // vazias e os filtros do painel viram seleções reais, então medidas governadas ($(=Max(Competência))…)
  // funcionam e as seleções do usuário não mudam. Sem sessão separada, cai no estado alternativo.
  var STATE = "DashBuilderAI_Snapshot", WIDTH = 1280;

  var PAGE_CSS = [
    "html, body { margin: 0; background: #f8fafc; font-family: 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; color: #334155; }",
    ".qdb { max-width: " + WIDTH + "px; margin: 0 auto; }",
    ".qdb .md-root { height: auto; }",
    ".qdb .md-painel { overflow: visible; padding: 20px 14px 8px; }",
    ".qdb .md-svg { max-width: 100%; height: auto; }",
    ".qdb [data-md-sel], .qdb [data-action] { cursor: default; }",
    ".qdb .md-tip { position: fixed; }",
    ".qdb-foot { max-width: " + WIDTH + "px; margin: 0 auto; padding: 4px 14px 24px; font-size: 11px; color: #94a3b8; }",
    "@media (max-width: 900px) { .qdb .md-tile { grid-column: span 12 !important; } }",
    "@media print { html, body { background: #fff; } .qdb .md-tile { break-inside: avoid; } }"
  ].join("\n");

  var TIP_JS = "(function(){var t=document.querySelector('.md-tip');if(!t)return;document.addEventListener('mousemove',function(e){" +
    "var n=e.target.closest&&e.target.closest('[data-tip]');if(!n){t.style.display='none';return;}t.textContent=n.getAttribute('data-tip');" +
    "t.style.display='block';var x=e.clientX+14,y=e.clientY+14;if(x+t.offsetWidth>innerWidth)x=e.clientX-t.offsetWidth-10;" +
    "if(y+t.offsetHeight>innerHeight)y=e.clientY-t.offsetHeight-10;t.style.left=x+'px';t.style.top=y+'px';});})();";

  // Cria (uma vez) o estado alternativo usado na extração. Sem ele, cai para o estado padrão.
  function ensureState(app) {
    var em;
    try { em = appinfo.engine(app); } catch (e) { return Promise.resolve(null); }
    return Promise.resolve(em.getAppLayout()).then(function (l) {
      if ((l.qStateNames || []).indexOf(STATE) >= 0) return STATE;
      return Promise.resolve(em.addAlternateState(STATE)).then(function () { return STATE; });
    }).then(null, function (e) {
      console.warn("DashBuilder AI: não foi possível criar o estado alternativo; as linhas podem seguir as seleções.", e);
      return null;
    });
  }

  function slug(s) {
    var def = T("painel", "panel");
    return String(s || def).normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^\w]+/g, "-").replace(/^-+|-+$/g, "").toLowerCase() || def;
  }

  function pageHtml(spec, inner, o, at, isolated) {
    var when = at.toLocaleString(i18n.locale()), esc = u.esc;
    // Atenção: o texto "com {1} nas medidas" tem chaves literais; por isso esse T() é chamado sem vars.
    return "<!doctype html>\n<html lang=\"" + i18n.locale() + "\"><head><meta charset=\"utf-8\">" +
      "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">" +
      "<meta name=\"generator\" content=\"Qlik DashBuilder AI\">" +
      "<title>" + esc(spec.title || T("Painel", "Panel")) + "</title>\n<style>\n" + cssscope.scope(o.baseCss, ".qdb") + "\n" + PAGE_CSS + "\n</style></head><body>\n" +
      "<div class=\"qdb\"><div class=\"md-root\"><div class=\"md-painel\">" + inner + "</div><div class=\"md-tip\"></div></div></div>\n" +
      "<div class=\"qdb-foot\">" + T("Gerado pelo Qlik DashBuilder AI em {when}", "Generated by Qlik DashBuilder AI on {when}", { when: esc(when) }) + (o.appTitle ? " · app " + esc(o.appTitle) : "") +
      " · " + (isolated ? T("dados fixos, extraídos sem considerar as seleções do Qlik", "fixed data, extracted without considering Qlik selections")
        : T("dados fixos, extraídos com {1} nas medidas (as linhas podiam seguir as seleções)", "fixed data, extracted with {1} in the measures (rows could follow the selections)")) +
      (spec.filterText ? " · " + T("filtro", "filter") + ": " + esc(spec.filterText) : "") + ".</div>\n" +
      "<script>" + TIP_JS + "</script>\n</body></html>\n";
  }

  // Sessão separada pronta: sem seleções e com os filtros fixos do painel selecionados.
  function openSession(spec) {
    return session.open("snap").then(function (app) {
      var include = spec.filters.filter(function (f) { return !f.exclude; });
      return appinfo.select(app, include).then(function () { return app; }, function (e) { session.release("snap"); throw e; });
    });
  }

  // Uma geração por vez: todas usam a mesma sessão separada e as seleções dela não podem se misturar.
  var line = Promise.resolve();
  function build(json, o) {
    var job = line.then(function () { return buildNow(json, o); });
    line = job.then(null, function () { /* a fila segue */ });
    return job;
  }

  // o: { baseCss, cfg, scope }  →  Promise<{ html, name, at, tiles, isolated, session }>
  function buildNow(json, o) {
    var spec = dash.parse(json), app = qlik.currApp();
    if (!spec || !spec.tiles.length) return Promise.reject(new Error(T("Não há painel para gerar o HTML.", "There is no panel to generate the HTML from.")));
    var title = Promise.resolve().then(function () { return appinfo.engine(app).getAppLayout(); }).then(function (l) { return l.qTitle; }, function () { return ""; });
    var where = openSession(spec).then(function (sApp) { return { app: sApp, stateName: null }; }, function (e) {
      console.warn("DashBuilder AI: sessão separada indisponível; usando o estado alternativo.", e);
      return ensureState(app).then(function (st) { return { app: app, stateName: st }; });
    });
    return Promise.all([where, title]).then(function (r) {
      var w = r[0], own = w.app !== app, stateName = w.stateName, host = document.createElement("div");
      host.className = o.scope;
      host.style.cssText = "position:fixed;left:-20000px;top:0;width:" + WIDTH + "px;pointer-events:none;";
      host.innerHTML = '<div class="md-root" style="height:auto"><div class="md-painel" style="overflow:visible"></div></div>';
      document.body.appendChild(host);
      var painel = host.querySelector(".md-painel"), st = dash.newState();
      dash.mount(st, painel, json, o.cfg, { app: w.app, stateName: stateName, noSidebar: true });
      var finish = function () {
        dash.destroy(st);
        if (host.parentNode) host.parentNode.removeChild(host);
        if (own) session.release("snap");
      };
      return dash.whenReady(st, 10 * 60 * 1000).then(function (complete) {
        var at = new Date(), inner = painel.innerHTML;
        finish();
        if (!complete) console.warn("DashBuilder AI: alguns blocos não carregaram a tempo para o HTML Complexo.");
        return {
          html: pageHtml(spec, inner, Object.assign({ appTitle: r[1] }, o), at, own || !!stateName),
          name: slug(spec.title) + "-" + at.toISOString().slice(0, 10) + ".html",
          at: at, tiles: spec.tiles.length, isolated: own || !!stateName, session: own, method: st.seriesMethod || null
        };
      }, function (e) { finish(); throw e; });
    });
  }

  function download(res, doc) {
    doc = doc || document;
    var url = URL.createObjectURL(new Blob([res.html], { type: "text/html;charset=utf-8" }));
    var a = doc.createElement("a");
    a.href = url;
    a.download = res.name;
    doc.body.appendChild(a);
    a.click();
    a.parentNode.removeChild(a);
    setTimeout(function () { URL.revokeObjectURL(url); }, 2000);
  }

  // A aba é aberta no clique (senão o navegador bloqueia) e preenchida quando o HTML fica pronto.
  function openTab(win) {
    var w = null;
    try { w = (win || window).open("", "_blank"); } catch (e) { w = null; }
    if (w) {
      try {
        w.document.write("<!doctype html><html lang=\"" + i18n.locale() + "\"><meta charset=\"utf-8\"><title>" + T("Gerando…", "Generating…") +
          "</title><p style=\"font-family:sans-serif;color:#64748b;padding:24px\">" + T("Gerando o painel em HTML…", "Generating the panel as HTML…") + "</p>");
      } catch (e) { /* ignorado */ }
    }
    return w;
  }

  function show(w, res) {
    w.document.open();
    w.document.write(res.html);
    w.document.close();
  }

  return { build: build, download: download, openTab: openTab, show: show, STATE: STATE };
});
